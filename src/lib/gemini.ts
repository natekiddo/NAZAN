import { GoogleGenAI } from '@google/genai';

if (typeof process !== 'undefined') {
  process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
}

let geminiClient: GoogleGenAI | null = null;
const GEMINI_MODEL = process.env.GEMINI_MODEL || 'gemini-3.8-flash';

function getGeminiClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'your-gemini-api-key' || apiKey.trim() === '') {
    return null;
  }

  if (!geminiClient) {
    try {
      geminiClient = new GoogleGenAI({ apiKey });
    } catch {
      geminiClient = null;
    }
  }

  return geminiClient;
}

/**
 * Call Gemini generateContent supporting both 'gemini-3.8-flash' and 'models/gemini-3.8-flash'
 */
async function callGeminiGenerate(ai: GoogleGenAI, contents: any) {
  try {
    return await ai.models.generateContent({
      model: GEMINI_MODEL,
      contents,
    });
  } catch (err: any) {
    // If the model name format requires the 'models/' prefix or vice versa
    const fallbackModel = GEMINI_MODEL.startsWith('models/')
      ? GEMINI_MODEL.replace('models/', '')
      : `models/${GEMINI_MODEL}`;
    try {
      return await ai.models.generateContent({
        model: fallbackModel,
        contents,
      });
    } catch {
      throw err;
    }
  }
}

