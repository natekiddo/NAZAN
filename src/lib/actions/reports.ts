'use server';

if (typeof process !== 'undefined') {
  process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
}

import { createClient } from '@/lib/supabase/server';
import { createAdminClient } from '@/lib/supabase/admin';
import { getEffectivePermissions } from '@/lib/permissions';

export async function exportProjectReportAction(
  projectId: string,
  format: 'markdown' | 'csv' = 'markdown'
): Promise<{ success: boolean; content?: string; filename?: string; error?: string }> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();

  if (!user) {
    return { success: false, error: 'Unauthorized: User not authenticated' };
  }

  const db = createAdminClient() || supabase;

  // 1. Fetch project
  const { data: project, error: projErr } = await db
    .from('projects')
    .select('*')
    .eq('id', projectId)
    .single();

  if (projErr || !project) {
    return { success: false, error: 'Project not found' };
  }

  // 2. Permission check: if belongs to workspace, check can_export_reports
  if (project.workspace_id) {
    const { data: member } = await db
      .from('workspace_members')
      .select('role, custom_permissions')
      .eq('workspace_id', project.workspace_id)
      .eq('user_id', user.id)
      .single();

    if (!member && project.user_id !== user.id) {
      return { success: false, error: 'Access denied: You are not a member of this workspace' };
    }

    if (member) {
      const perms = getEffectivePermissions(member.role, member.custom_permissions);
      if (!perms.can_export_reports && project.user_id !== user.id) {
        return { success: false, error: 'Permission denied: You do not have permission to export reports' };
      }
    }
  }

  // 3. Fetch project tasks, milestones, notes, sessions
  const [tasksRes, milestonesRes, sessionsRes] = await Promise.all([
    db
      .from('tasks')
      .select('*')
      .eq('project_id', projectId)
      .order('due_date', { ascending: true }),
    db
      .from('milestones')
      .select('*')
      .eq('project_id', projectId)
      .order('due_date', { ascending: true }),
    db
      .from('work_sessions')
      .select('*')
      .eq('project_id', projectId)
      .order('start_time', { ascending: false })
      .limit(10),
  ]);

  const tasks = tasksRes.data || [];
  const milestones = milestonesRes.data || [];
  const sessions = sessionsRes.data || [];

  const sanitizedName = project.name.replace(/[^a-zA-Z0-9_-]/g, '_');

  if (format === 'csv') {
    const csvRows = [
      ['Task ID', 'Title', 'Status', 'Priority', 'Due Date', 'Created At'],
      ...tasks.map((t) => [
        t.id,
        `"${t.title.replace(/"/g, '""')}"`,
        t.status,
        t.priority,
        t.due_date || 'N/A',
        t.created_at,
      ]),
    ];

    const csvContent = csvRows.map((r) => r.join(',')).join('\n');
    return {
      success: true,
      content: csvContent,
      filename: `${sanitizedName}_tasks_report.csv`,
    };
  }

  // Default: Markdown report
  const completedTasks = tasks.filter((t) => t.status === 'Completed');
  const pendingTasks = tasks.filter((t) => t.status !== 'Completed');

  const mdReport = `# Project Status & Executive Report: ${project.name}
> Generated by **ProjectHub Workspace Intelligence** on ${new Date().toLocaleString()}

---

## 1. Executive Summary
* **Project Name:** ${project.name}
* **Status:** ${project.status} (Progress: ${project.progress}%)
* **Priority:** ${project.priority}
* **Category:** ${project.category || 'General'}
* **Deadline:** ${project.deadline || 'No deadline set'}
* **Next Action:** ${project.next_action || 'None recorded'}

### Description:
${project.description || 'No description provided.'}

---

## 2. Sprint Tasks Breakdown
* **Total Tasks:** ${tasks.length}
* **Completed:** ${completedTasks.length} (${tasks.length > 0 ? Math.round((completedTasks.length / tasks.length) * 100) : 0}%)
* **Pending / In Progress:** ${pendingTasks.length}

### Pending Tasks:
${
  pendingTasks.length > 0
    ? pendingTasks
        .map(
          (t, i) =>
            `${i + 1}. **${t.title}** — [Priority: \`${t.priority}\`, Status: \`${t.status}\`${t.due_date ? `, Due: ${t.due_date}` : ''}]`
        )
        .join('\n')
    : '* 🎉 No pending tasks in this project!'
}

### Completed Tasks:
${
  completedTasks.length > 0
    ? completedTasks.map((t, i) => `${i + 1}. [x] **${t.title}**`).join('\n')
    : '* No completed tasks yet.'
}

---

## 3. Milestones
${
  milestones.length > 0
    ? milestones
        .map(
          (m, i) =>
            `${i + 1}. **${m.title}** — [${m.completed ? 'Completed' : 'Pending'}${m.due_date ? `, Due: ${m.due_date}` : ''}]`
        )
        .join('\n')
    : '* No milestones configured.'
}

---

## 4. Recent Work Sessions & Stopping Points
${
  sessions.length > 0
    ? sessions
        .map(
          (s, i) =>
            `### Session ${i + 1}: ${s.title} (${new Date(s.start_time).toLocaleDateString()}, ${s.duration_mins} mins)\n* **Completed:** ${s.work_completed || 'Focused work'}\n* **Next Action:** ${s.next_action || 'None'}\n* **Blockers:** ${s.blockers || 'None'}`
        )
        .join('\n\n')
    : '* No work sessions logged yet.'
}

---
*Report exported from ProjectHub Cloud Workspace.*`;

  return {
    success: true,
    content: mdReport,
    filename: `${sanitizedName}_status_report.md`,
  };
}
